import { beforeAll, describe, expect, it } from 'vitest';
import { createVault, decryptRecord, derive, encryptRecord, open, ready, recoverDeviceKey, seal, sodium, unlock, wipe } from '../src/crypto';
import { aad, CHUNK_BYTES, context, MAX_ATTACHMENT_BYTES, validateKdf, type Kdf } from '../src/format';
import { chunkAad, readAttachment, startAttachment } from '../src/attachments';

beforeAll(ready);
const kdf = (): Kdf => ({ algorithm: 'argon2id13', memory: 64 * 1024 ** 2, passes: 3, salt: new Uint8Array(16).fill(42) });
describe('cryptographic boundaries', () => {
  it('matches the published libsodium 1.0.20 XChaCha20-Poly1305 vector', () => {
    // https://github.com/jedisct1/libsodium/blob/1.0.20/test/default/aead_xchacha20poly1305.c
    // Expected first ciphertext in the sibling .exp file, not generated by this implementation.
    const key = Uint8Array.from({ length: 32 }, (_, i) => 0x80 + i);
    const nonce = sodium.from_hex('07000000404142434445464748494a4b4c4d4e4f50515253');
    const ad = sodium.from_hex('50515253c0c1c2c3c4c5c6c7');
    const text = "Ladies and Gentlemen of the class of '99: If I could offer you only one tip for the future, sunscreen would be it.";
    const actual = sodium.crypto_aead_xchacha20poly1305_ietf_encrypt(text, ad, null, nonce, key);
    expect(sodium.to_hex(actual)).toBe('f8ebea4875044066fc162a0604e171feecfb3d20425248563bcfd5a155dcc47bbda70b86e5ab9b55002bd1274c02db35321acd7af8b2e2d25015e136b7679458e9f43243bf719d639badb5feac03f80a19a96ef10cb1d15333a837b90946ba3854ee74da3f2585efc7e1e170e17e15e563e77601f4f85cafa8e5877614e143e68420');
  });
  it('encodes deterministic CBOR with binary UUIDs', () => {
    const id = '00000000-0000-0000-0000-000000000001';
    expect(sodium.to_hex(aad('record', { vaultId: id, objectId: id, revisionId: id, epoch: 1 }))).toBe('876d766f6c747572612d7661756c7401667265636f726450000000000000000000000000000000010150000000000000000000000000000000015000000000000000000000000000000001');
  });
  it('round-trips Unicode and exact stored-secret whitespace without normalization', () => {
    const key = sodium.randombytes_buf(32), c = context();
    const text = '  Räksmörgås a\u030a 🔐\r\n\t åäö  ';
    const r = encryptRecord(text, key, c, []);
    expect(decryptRecord(r, key, c)).toBe(text); wipe(key);
  });
  it('rejects wrong keys, changed AAD, truncated ciphertext, and every tampered byte', () => {
    const key = sodium.randombytes_buf(32), c = context(), box = seal(sodium.from_string('canary'), key, 'record', c);
    expect(() => open(box, sodium.randombytes_buf(32), 'record', c)).toThrow();
    expect(() => open(box, key, 'record-key', c)).toThrow();
    expect(() => open(box, key, 'record', { ...c, epoch: 2 })).toThrow();
    expect(() => open(box, key, 'record', { ...c, objectId: crypto.randomUUID() })).toThrow();
    for (let i = 0; i < box.ciphertext.length; i++) {
      const b = structuredClone(box); b.ciphertext[i] ^= 1;
      expect(() => open(b, key, 'record', c)).toThrow();
    }
    expect(() => open({ ...box, ciphertext: box.ciphertext.slice(0, -1) }, key, 'record', c)).toThrow();
  });
  it('normalizes only master passwords to NFC without trimming', () => {
    const a = derive('  a\u030a ', kdf()), b = derive('  å ', kdf()), c = derive('å', kdf());
    expect(a).toEqual(b); expect(a).not.toEqual(c); [a, b, c].forEach(wipe);
  });
  it('unlocks a master envelope and rejects a wrong password', () => {
    const v = createVault('synthetic-test', kdf());
    const key = unlock('synthetic-test', v.envelope); expect(key).toEqual(v.root); wipe(key);
    expect(() => unlock('wrong-test', v.envelope)).toThrow(); wipe(v.root);
  });
  it('requires a device key and authenticates recovery against the vault envelope', () => {
    const device = sodium.randombytes_buf(32), recovery = sodium.randombytes_buf(32);
    const account = sodium.randombytes_buf(32);
    const { root, envelope } = createVault('synthetic-test', kdf(), account, { deviceKey: device, recoveryKey: recovery });
    try {
      expect(() => unlock('synthetic-test', envelope)).toThrow('device key');
      const stripped = { ...envelope, recoveryDevice: undefined };
      expect(() => unlock('synthetic-test', stripped)).toThrow();
      expect(() => recoverDeviceKey(envelope, new Uint8Array(32))).toThrow();
      const tampered = structuredClone(envelope);
      tampered.recoveryDevice!.ciphertext[0] ^= 1;
      expect(() => recoverDeviceKey(tampered, recovery)).toThrow();
      const transplanted = { ...envelope, context: { ...envelope.context, vaultId: crypto.randomUUID() } };
      expect(() => recoverDeviceKey(transplanted, recovery)).toThrow();
      const recovered = recoverDeviceKey(envelope, recovery);
      try {
        expect(() => unlock('wrong-test', envelope, undefined, recovered)).toThrow();
        const key = unlock('synthetic-test', envelope, value => expect(value).toEqual(account), recovered);
        try { expect(key).toEqual(root); } finally { wipe(key); }
      } finally { wipe(recovered); }
    } finally { [device, recovery, account, root].forEach(wipe); }
  });
  it('accepts a record only under the active key generation', () => {
    const oldKey = sodium.randombytes_buf(32), newKey = sodium.randombytes_buf(32), prior = context();
    const next = { ...prior, epoch: 2 };
    try {
      const old = encryptRecord('before rotation', oldKey, prior, []);
      const rotated = encryptRecord(decryptRecord(old, oldKey, prior), newKey, next, []);
      expect(decryptRecord(rotated, newKey, next)).toBe('before rotation');
      expect(() => decryptRecord(rotated, oldKey, next)).toThrow();
      expect(() => decryptRecord(rotated, newKey, prior)).toThrow('key epoch');
      expect(() => decryptRecord(old, oldKey, next)).toThrow('key epoch');
    } finally { [oldKey, newKey].forEach(wipe); }
  });
  it('allocates fresh content keys and nonces on each rewrite', () => {
    const root = sodium.randombytes_buf(32), c = context();
    const a = encryptRecord('same', root, c, []), b = encryptRecord('same', root, c, []);
    expect(a.key.nonce).not.toEqual(b.key.nonce); expect(a.body.nonce).not.toEqual(b.body.nonce);
    expect(a.body.ciphertext).not.toEqual(b.body.ciphertext);
  });
  it.each([0, -1, 32 * 1024 ** 2, 1024 ** 3, NaN, Infinity])('bounds KDF memory before allocation: %s', memory => {
    expect(() => validateKdf({ ...kdf(), memory })).toThrow();
  });
  it.each([0, 1, 2, 65, 3.5, Infinity, NaN])('bounds KDF passes: %s', passes => {
    expect(() => validateKdf({ ...kdf(), passes })).toThrow();
  });
  it('rejects oversized notes, invalid identifiers, and unexpected format versions', () => {
    expect(() => aad('record', { ...context(), objectId: '../escape' })).toThrow();
    expect(() => encryptRecord('a'.repeat(1_000_001), sodium.randombytes_buf(32), context(), [])).toThrow();
    const c = context(), root = sodium.randombytes_buf(32), record = encryptRecord('test', root, c, []);
    expect(() => decryptRecord({ ...record, version: 2 } as never, root, c)).toThrow();
  });
});

describe('attachment authentication', () => {
  async function fixture(size = CHUNK_BYTES + 5) {
    const root = sodium.randombytes_buf(32), c = context(), { attachment, state } = startAttachment(root, c, size);
    const chunks = [];
    for (let i = 0; i < attachment.chunks; i++) {
      chunks.push(sodium.crypto_secretstream_xchacha20poly1305_push(state, new Uint8Array(Math.min(CHUNK_BYTES, size - i * CHUNK_BYTES)).fill(i), chunkAad(c, i), i === attachment.chunks - 1 ? 3 : 0));
    }
    return { root, c, attachment, chunks };
  }
  it('authenticates all bytes and the final marker across chunk boundaries', async () => {
    const f = await fixture(); let size = 0;
    await readAttachment(f.attachment, f.root, f.c, async i => f.chunks[i], async bytes => { size += bytes.length; });
    expect(size).toBe(CHUNK_BYTES + 5);
  });
  it('refuses a stale attachment before reading any chunks', async () => {
    const f = await fixture(0);
    let read = false;
    await expect(readAttachment(f.attachment, f.root, { ...f.c, epoch: 2 }, async () => {
      read = true;
      return f.chunks[0];
    }, async () => {})).rejects.toThrow('Invalid attachment metadata');
    expect(read).toBe(false);
  });
  it('round-trips the full 100 MB attachment limit', async () => {
    const root = sodium.randombytes_buf(32), c = context();
    const { attachment, state } = startAttachment(root, c, MAX_ATTACHMENT_BYTES);
    let verifiedBytes = 0;
    let chunk = 0;
    try {
      await readAttachment(attachment, root, c, async index => {
        const size = Math.min(CHUNK_BYTES, MAX_ATTACHMENT_BYTES - index * CHUNK_BYTES);
        const plain = new Uint8Array(size).fill(index);
        try {
          const tag = index === attachment.chunks - 1
            ? sodium.crypto_secretstream_xchacha20poly1305_TAG_FINAL
            : sodium.crypto_secretstream_xchacha20poly1305_TAG_MESSAGE;
          return sodium.crypto_secretstream_xchacha20poly1305_push(state, plain, chunkAad(c, index), tag);
        } finally { wipe(plain); }
      }, async bytes => {
        expect(bytes.every(byte => byte === chunk)).toBe(true);
        chunk++;
        verifiedBytes += bytes.length;
      });
      expect(chunk).toBe(96);
      expect(verifiedBytes).toBe(100_000_000);
    } finally { wipe(root); }
  });
  it('handles an authenticated empty file', async () => {
    const f = await fixture(0);
    await readAttachment(f.attachment, f.root, f.c, async i => f.chunks[i], async bytes => { expect(bytes.length).toBe(0); });
  });
  it('rejects missing chunks, truncation, reordering, and mismatched metadata', async () => {
    const f = await fixture(); const discard = async () => {};
    await expect(readAttachment(f.attachment, f.root, f.c, async i => f.chunks[i]?.slice(0, -1), discard)).rejects.toThrow();
    await expect(readAttachment(f.attachment, f.root, f.c, async i => f.chunks[1 - i], discard)).rejects.toThrow();
    await expect(readAttachment({ ...f.attachment, chunks: 1 }, f.root, f.c, async i => f.chunks[i], discard)).rejects.toThrow();
    await expect(readAttachment({ ...f.attachment, size: CHUNK_BYTES, chunks: 1 }, f.root, f.c, async i => f.chunks[i], discard)).rejects.toThrow('Truncated');
  });
  it('rejects invalid lengths before creating a stream', () => {
    for (const size of [-1, 100_000_001, Infinity, 0.5]) expect(() => startAttachment(sodium.randombytes_buf(32), context(), size)).toThrow();
  });
});
